/** 쪽마다 붙는 그림. 새 이미지를 만들지 않고 심볼과 도형으로만 그린다. */
enum class OnboardingArt { SYMBOL, WEEK_BARS, CALIBRATION, FRAMING }

/**
 * 온보딩 한 쪽.
 *
 * @property body 한 줄이면 문단, 여러 줄이면 목록으로 그린다.
 * @property note 보조 문구. 값의 성격(어림값·설정에서 바꿀 수 있음)을 밝히는 자리다.
 */
data class OnboardingPage(
    val title: String,
    val body: List<String>,
    val note: String? = null,
    val art: OnboardingArt,
)

